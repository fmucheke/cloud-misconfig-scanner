"""
remediation_writer.py

Takes one enriched finding (raw finding + control_mapping + severity, as
produced by scan.py) and generates a plain-English remediation paragraph
using the Anthropic API.

This is the ONLY place in the pipeline where an LLM is involved. Every
fact the LLM is given — the issue, the mapped control, the severity — was
already determined by the deterministic, human-verified layers built in
Sessions 1-9. The LLM's job is narrow and specific: turn verified facts
into readable prose for a non-technical audience. It does not decide
what's true, and it's explicitly instructed not to invent detail beyond
what it's given.
"""

import os
from dotenv import load_dotenv
import anthropic

load_dotenv()

client = anthropic.Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY"))

MODEL = "claude-sonnet-4-6"

SYSTEM_PROMPT = """You are a cloud security consultant writing remediation guidance for a client report. Your audience is mixed: some readers are technical (engineers, IT staff), others are not (executives, compliance officers). Write ONE paragraph (4-6 sentences) that:

1. States what the misconfiguration is and why it matters, in plain English — avoid unexplained jargon.
2. Briefly explains the real-world risk if left unaddressed (what could actually happen).
3. Gives a clear, specific, actionable remediation step.
4. Names the SPECIFIC control identifiers provided to you, worked naturally into a sentence rather than listed as a citation dump. "Naturally" means conversational phrasing, NOT vague — you must state the exact control codes given to you (e.g. "Security Hub control IAM.1" and "CIS AWS Foundations Benchmark v1.4.0 control 1.16" and "NIST CSF 2.0 PR.AA-05"), never a generic paraphrase like "the CIS Benchmark" or "relevant NIST guidance" with no code attached. If no CIS control number was provided, say so explicitly rather than omitting it or gesturing vaguely at "the CIS Benchmark."

Strict rules:
- Use ONLY the facts provided to you. Do not invent specifics that were not given — no made-up timelines, tool names, root causes, or details about the environment beyond what's in the input.
- Do not use headers, bullet points, or markdown. One plain paragraph only.
- Do not restate the raw JSON field names (e.g. don't write "the finding_type is..."). Write like a human report, not a data dump.
- Match the tone to the severity: CRITICAL findings should read with real urgency; MEDIUM findings should read as a real but less pressing gap."""


def build_user_message(finding):
    """
    Builds the structured input the LLM sees, pulling only the fields
    relevant to writing a remediation paragraph — not the entire raw
    finding dict, which would include internal bookkeeping fields like
    lookup_error or severity_hint that the LLM doesn't need to see.
    """
    control = finding.get("control_mapping", {})

    cis_line = (
        f"CIS AWS Foundations Benchmark {control.get('cis_control')} ({control.get('cis_version')})"
        if control.get("cis_control")
        else "no CIS Benchmark control number confirmed for this check"
    )

    return f"""Resource type: {finding.get('resource_type')}
Resource name: {finding.get('resource_name')}
Issue: {finding.get('issue')}
Severity: {finding.get('severity')}
Details: {finding.get('details')}

Compliance mapping:
- AWS Security Hub control: {control.get('security_hub_control')} — {control.get('security_hub_title')}
- {cis_line}
- NIST CSF 2.0: {control.get('nist_csf')} — {control.get('nist_csf_title')}

Write the remediation paragraph now."""


def generate_remediation(finding):
    """
    Takes one enriched finding dict and returns a remediation paragraph
    (plain string) generated by Claude.
    """
    user_message = build_user_message(finding)

    response = client.messages.create(
        model=MODEL,
        max_tokens=450,  # increased from 300 — the tightened prompt now produces longer, more specific paragraphs and 300 was cutting them off mid-sentence
        temperature=0.3,  # low temperature: favor consistency/accuracy over creative variation
        system=SYSTEM_PROMPT,
        messages=[{"role": "user", "content": user_message}]
    )

    return response.content[0].text


